import { themes, type SemanticColors } from "./tokens/color.js";
import { elevation, zIndex } from "./tokens/elevation.js";
import { MIN_HIT_TARGET } from "./tokens/layout.js";
import { motion, reducedMotion, type CubicBezier, type Motion } from "./tokens/motion.js";
import { radius } from "./tokens/radius.js";
import { safeZones } from "./tokens/safe-zones.js";
import { space } from "./tokens/spacing.js";
import { fontSize, fontStack, fontWeight, lineHeight } from "./tokens/typography.js";

const kebab = (name: string) => name.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

/** The CSS custom property for a token, such as `cssVar("color", "textMuted")` → `--sr-color-text-muted`. */
export function cssVar(group: string, name: string | number): string {
  return `--sr-${group}-${kebab(String(name))}`;
}

type Declarations = [property: string, value: string | number][];

const entries = <T extends object>(tokens: T) => Object.entries(tokens) as [string, T[keyof T]][];
const bezier = (curve: CubicBezier) => `cubic-bezier(${curve.join(", ")})`;

function colorDeclarations(colors: SemanticColors): Declarations {
  return entries(colors).map(([role, value]) => [cssVar("color", role), value]);
}

function motionDeclarations(tokens: Motion): Declarations {
  return [
    ...entries(tokens.duration).map(([name, ms]): Declarations[number] => [cssVar("duration", name), `${ms}ms`]),
    ...entries(tokens.easing).map(([name, curve]): Declarations[number] => [cssVar("easing", name), bezier(curve)]),
  ];
}

function staticDeclarations(): Declarations {
  return [
    [cssVar("font", "ui"), fontStack.ui],
    [cssVar("font", "mono"), fontStack.mono],
    ...entries(fontSize).map(([name, px]): Declarations[number] => [cssVar("font-size", name), `${px}px`]),
    ...entries(fontWeight).map(([name, weight]): Declarations[number] => [cssVar("font-weight", name), weight]),
    ...entries(lineHeight).map(([name, ratio]): Declarations[number] => [cssVar("line-height", name), ratio]),
    ...entries(space).map(([name, px]): Declarations[number] => [cssVar("space", name), `${px}px`]),
    ...entries(radius).map(([name, px]): Declarations[number] => [cssVar("radius", name), `${px}px`]),
    ...entries(elevation).map(([level, s]): Declarations[number] => [
      cssVar("shadow", level),
      s.opacity === 0 ? "none" : `0 ${s.offsetY}px ${s.blur}px rgba(0, 0, 0, ${s.opacity})`,
    ]),
    ...entries(zIndex).map(([name, z]): Declarations[number] => [cssVar("z", name), z]),
    ...motionDeclarations(motion),
    [cssVar("hit-target", "min"), `${MIN_HIT_TARGET}px`],
    [cssVar("canvas", "aspect"), "9 / 16"],
    ...entries(safeZones).flatMap(([preset, insets]) =>
      entries(insets).map(([side, value]): Declarations[number] => [cssVar("safe-zone", `${preset}-${side}`), value]),
    ),
  ];
}

function block(selector: string, declarations: Declarations, indent = ""): string {
  const body = declarations.map(([property, value]) => `${indent}  ${property}: ${value};`).join("\n");
  return `${indent}${selector} {\n${body}\n${indent}}`;
}

/**
 * Renders every token as CSS custom properties. `:root` holds the dark theme (the default) and
 * `[data-theme="light"]` switches to light. Reduced motion zeroes the durations.
 */
export function renderTokensCss(): string {
  const parts = [
    "/* Generated by @stackreel/ui (scripts/build-css.ts). Do not edit. */",
    block(":root", [["color-scheme", "dark"], ...colorDeclarations(themes.dark), ...staticDeclarations()]),
    block('[data-theme="light"]', [["color-scheme", "light"], ...colorDeclarations(themes.light)]),
    `@media (prefers-reduced-motion: reduce) {\n${block(":root", motionDeclarations(reducedMotion), "  ")}\n}`,
  ];
  return `${parts.join("\n\n")}\n`;
}
