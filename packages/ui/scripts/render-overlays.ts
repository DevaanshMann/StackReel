import { fileURLToPath } from "node:url";
import { renderSafeZoneOverlaySvg } from "../src/overlays.js";
import { safeZones, type SafeZonePresetName } from "../src/tokens/safe-zones.js";

export const OVERLAYS_DIR = fileURLToPath(new URL("../overlays/", import.meta.url));

/** Every preset except `none`, which covers nothing. */
export const OVERLAY_PRESETS = (Object.keys(safeZones) as SafeZonePresetName[]).filter((preset) => preset !== "none");

export const overlayFileName = (preset: SafeZonePresetName) => `${preset}.svg`;

const header = "<!-- Generated by @stackreel/ui (scripts/generate-overlays.ts). Do not edit. -->";

/** A committed overlay file's exact contents. */
export function renderOverlayFile(preset: SafeZonePresetName): string {
  return `${header}\n${renderSafeZoneOverlaySvg(preset)}`;
}
